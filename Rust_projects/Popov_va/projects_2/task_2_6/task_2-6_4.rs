use std::io;

fn main() {
    println!("=== Богатырь на распутье ===\n");
    println!("Стоит богатырь у камня на перекрёстке трёх дорог.");
    println!("На камне высечено:\n");
    println!("  Налево пойдёшь  — коня потеряешь");
    println!("  Направо пойдёшь — себя потеряешь");
    println!("  Прямо пойдёшь   — богатым будешь\n");

    println!("Куда пойдёшь, богатырь? (налево / направо / прямо):");
    let mut input = String::new();
    io::stdin().read_line(&mut input).expect("Ошибка ввода");
    let path = input.trim().to_lowercase();

    if path == "налево" || path == "налево пойду" {
        println!("\nТы пошёл налево...");
        println!("Конь твой сбился с пути и исчез в тумане.");
        println!("Потерял ты верного товарища, но сам остался жив.");
        println!("Иди теперь пешком, богатырь.");
    } else if path == "направо" || path == "направо пойду" {
        println!("\nТы пошёл направо...");
        println!("Заблудился ты в дремучем лесу.");
        println!("Потерял себя — не помнишь ни имени, ни пути домой.");
        println!("Бродить тебе по лесу, пока кто не найдёт.");
    } else if path == "прямо" || path == "прямо пойду" {
        println!("\nТы пошёл прямо...");
        println!("Пришёл ты к городу богатому.");
        println!("Приняли тебя с почестями, наградили золотом и славой.");
        println!("Стал ты богатым и знаменитым богатырём!");
    } else {
        println!("\nНеверный выбор, богатырь.");
        println!("На камне написано только три пути: налево, направо или прямо.");
        println!("Вернись к камню и выбери правильно.");
    }
}