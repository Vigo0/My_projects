fn main() {
    println!("Hello world!");
    println!("2+2 = {}", 2 + 2);

// форматированный вывод.

    let name = "Алексей";
    let age = 30;
    let score = 95.5;

    // {} — автоматическая подстановка по порядку
    println!("Имя: {}, возраст: {}, балл: {}", name, age, score);

    // {:?} — вывод для отладки (Debug)
    let numbers = vec![1, 2, 3];
    println!("Числа: {:?}", numbers);

    // {:#?} — красивый Debug с отступами
    println!("Числа: {:#?}", numbers);

    println!("{0} и {1}", "первый", "второй");
    println!("{1} и {0}", "первый", "второй");  // поменяли порядок
    println!("{0}, {0}, {0}!", "повтор"); 
}